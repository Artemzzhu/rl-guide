Формально RL описывает задачу последовательного принятия решений. Агент выбирает действие не изолированно, а внутри процесса, где каждый шаг влияет на следующие состояния, будущие действия и будущие награды.

Обычно задача задается как марковский процесс принятия решений (MDP). В MDP выделяют:

S — пространство состояний;
A — пространство действий;
P(s'|s,a) — вероятность перехода в состояние s' после действия a в состоянии s;
R(s,a,s') — функция награды;
γ — коэффициент дисконтирования.

Марковское свойство означает, что для прогнозирования следующего состояния достаточно текущего состояния и действия. Прошлая история уже "сжата" в текущем состоянии. Это сильное допущение, но оно делает задачу математически удобной и лежит в основе многих алгоритмов RL.

Цель агента — максимизировать возврат, то есть суммарную награду за траекторию. Для бесконечного или длинного горизонта часто используют дисконтированный возврат:

G_t = R_t + γR_{t+1} + γ^2R_{t+2} + ...

Коэффициент γ находится в диапазоне от 0 до 1. Если γ близок к 0, агент почти полностью ориентируется на ближайшую награду. Если γ близок к 1, будущие награды становятся почти такими же важными, как текущие. Это позволяет моделировать задачи, где результат действия проявляется не сразу.

Пример: робот идет вперед. Немедленная награда может поощрять скорость, но слишком резкие движения увеличивают риск падения. При большом γ агент учитывает будущие последствия и выбирает более устойчивое поведение.

Дисконтирование полезно не только интуитивно, но и технически: оно ограничивает вклад далекого будущего и делает сумму наград более управляемой при длинных эпизодах.
