Исследование и использование — одна из центральных дилемм RL. Агент должен одновременно применять уже найденные хорошие действия и пробовать новые действия, которые могут оказаться лучше.

Использование (exploitation) означает выбор действия с наилучшей текущей оценкой. Если агент уже знает, что определенный ход дает высокую награду, он может повторять его и получать стабильный результат.

Исследование (exploration) означает намеренную проверку менее известных действий. Такое действие может дать худшую награду сейчас, но открыть путь к лучшей стратегии в будущем.

Если агент слишком много исследует, обучение становится медленным: он часто пробует случайные варианты и теряет уже найденное качество. Если агент слишком рано переходит к использованию, он может застрять в локально хорошей, но не оптимальной стратегии. Например, игрок может постоянно применять одну рабочую тактику и не обнаружить более сильную.

Один из простых способов баланса — ε-жадная стратегия. С вероятностью 1 - ε агент выбирает действие с максимальной оценкой, а с вероятностью ε пробует случайное действие. В начале обучения ε можно делать большим, чтобы собрать разнообразный опыт. Затем ε постепенно уменьшают, чтобы агент чаще использовал найденную стратегию.

Проблема особенно заметна при разреженных наградах. Если награда появляется только после длинной последовательности действий, агенту трудно понять, какие ранние шаги были важны. Поэтому методы исследования помогают агенту не ограничиваться первым найденным поведением.

В практических алгоритмах исследование может задаваться не только случайными действиями, но и шумом в стратегии, стратегией Больцмана, верхней доверительной границей, внутренней мотивацией или специальными бонусами за новизну.
