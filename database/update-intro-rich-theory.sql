Обучение с подкреплением рассматривает обучение через взаимодействие. Агент не получает готовый набор правильных ответов, как в обучении с учителем. Вместо этого он выполняет действие, наблюдает результат и получает награду, которая показывает, насколько полезным оказалось поведение с точки зрения цели.

Основные элементы RL:

Агент — объект, принимающий решения. В игре это персонаж или программа, в робототехнике — контроллер робота, в задаче управления транспортом — система, выбирающая ускорение, торможение или поворот.

Среда — все, с чем агент взаимодействует. Она принимает действие агента и возвращает новое состояние и награду. Среда может быть виртуальной, как симулятор CartPole или игра Atari, либо физической, как робот или автомобиль.

Состояние S_t — описание текущей ситуации. В простой задаче это могут быть координаты в лабиринте; в CartPole — положение тележки, скорость, угол стержня и угловая скорость; в игре Atari — изображение экрана.

Действие A_t — выбор, который агент может сделать в текущем состоянии. Действия бывают дискретными, например "влево" или "вправо", и непрерывными, например значение крутящего момента двигателя.

Награда R_t — численный сигнал обратной связи. Она не обязательно говорит, какое действие было правильным, но задает направление обучения. Например, +1 за удержание стержня, +100 за выход из лабиринта или штраф за столкновение.

Цикл RL можно записать так:
S_t -> A_t -> R_t, S_{t+1}.

Последовательность таких шагов образует опыт агента. Отрезок взаимодействия от начального состояния до завершения задачи называется эпизодом, а последовательность состояний, действий и наград — траекторией. Агенту обычно требуется много эпизодов, чтобы накопить достаточно опыта и улучшить стратегию.

Важная особенность RL — задержка последствий. Действие может не дать немедленной награды, но изменить будущую траекторию. Поэтому агент должен учиться не только реагировать на текущий сигнал, но и оценивать долгосрочный эффект поведения.

Пример: лабиринт. Агент находится в клетке, состояние задается координатами, действия — перемещения вверх, вниз, влево и вправо. Награда может быть +100 за выход и -1 за каждый шаг. Тогда агенту выгодно не просто найти выход, а сделать это коротким путем.
