Стратегия и функции ценности отвечают на два разных вопроса: "как действовать?" и "насколько хороша ситуация или действие?".

Стратегия, или policy, задает правило выбора действия. Детерминированная стратегия возвращает одно действие для состояния:

a = μ(s).

Стохастическая стратегия задает распределение вероятностей:

π(a|s).

Второй вариант важен для исследования и для задач, где полезно сохранять случайность поведения.

Функция ценности состояния V^π(s) оценивает ожидаемый возврат, если агент начинает из состояния s и дальше действует по стратегии π. Она показывает, насколько состояние перспективно.

Функция ценности действия Q^π(s,a) оценивает ожидаемый возврат, если агент находится в состоянии s, сначала выбирает действие a, а затем продолжает действовать по стратегии π. Поэтому Q-функция напрямую помогает выбрать действие: можно сравнить Q(s,a) для доступных действий и взять действие с наибольшим значением.

Связь между V и Q можно понимать так: V(s) оценивает состояние в целом, а Q(s,a) оценивает конкретный вариант действия в этом состоянии. В задачах без известной модели среды Q-функция особенно удобна, потому что агенту не нужно заранее знать, в какое состояние приведет каждое действие.

Пример: шахматы. V(s) показывает, насколько хороша текущая позиция. Q(s,a) показывает, насколько хорош конкретный ход из этой позиции. Если известны Q-значения для всех легальных ходов, агент может выбрать ход с максимальной ожидаемой полезностью.

Многие алгоритмы RL строятся вокруг оценки этих функций: SARSA и Q-learning учатся оценивать Q(s,a), методы actor-critic совмещают стратегию и оценку ценности, а DQN аппроксимирует Q-функцию нейронной сетью.
