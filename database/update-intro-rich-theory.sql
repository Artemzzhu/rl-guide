В центре RL находится агент, который принимает решения в среде. На каждом шаге агент наблюдает состояние или наблюдение, выбирает действие, получает численную награду и переходит к следующему состоянию. В отличие от обучения с учителем, агенту обычно не сообщают "правильный ответ" для каждого состояния. Вместо этого он должен оценивать последствия собственных действий и постепенно строить стратегию, максимизирующую суммарную награду.

Главная сложность RL состоит в последовательности решений: действие может быть выгодным сейчас, но ухудшать будущие состояния, или наоборот, давать малую немедленную награду, но открывать путь к большому результату. Поэтому в RL важны понятия возврата, дисконтирования, стратегии, функций ценности и баланса между исследованием и использованием.

