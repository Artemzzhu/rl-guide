Обучение с подкреплением отличается от обучения с учителем и обучения без учителя не только типом данных, но и самой постановкой задачи.

В обучении с учителем есть набор примеров: вход и правильный ответ. Модель учится приближать ответы на фиксированном наборе данных. Ошибка вычисляется сразу: если модель предсказала неверную метку, это видно непосредственно.

В обучении без учителя правильных ответов нет. Модель ищет структуру в данных: группы похожих объектов, скрытые факторы, сжатое представление или распределение.

В RL у агента тоже нет правильного ответа для каждого состояния. Он получает только награду, причем награда может быть редкой или запаздывающей. Агент сам создает данные, потому что его стратегия влияет на то, какие состояния он посетит дальше. Это делает RL более интерактивной и нестабильной постановкой.

Ключевые отличия RL:

1. Нет оракула. Система не сообщает, какое действие было идеальным. Есть только численная обратная связь.

2. Данные зависят от поведения агента. Если агент всегда выбирает одни и те же действия, он может никогда не увидеть важные состояния.

3. Награда может быть разреженной. В шахматах или сложной игре главный сигнал может появиться только в конце партии.

4. Действия имеют долгосрочные последствия. Хорошее решение оценивается не только текущей выгодой, но и будущей траекторией.

Пример: в игре агент может получить награду только за победу в конце. Тогда отдельные ходы не имеют прямых меток "правильно" или "неправильно", но именно они постепенно приводят к выигрышной или проигрышной позиции.
